"""Regenerates src/sie/workspace/_font_data.py: ASCII glyph bitmaps cut from DejaVu Sans (free licence,
see docs/WORKSPACE_EXPORTS.md). Needs Pillow and matplotlib's bundled fonts; the product does not.

    python tools/make_font.py
"""

from __future__ import annotations

import base64
import json
import os
import zlib

import matplotlib
from PIL import Image, ImageDraw, ImageFont

SIZES = {"regular": ("DejaVuSans.ttf", 22), "bold": ("DejaVuSans-Bold.ttf", 26)}


def glyphs(font_file: str, size: int) -> dict[str, object]:
    path = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", font_file)
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    out: dict[str, object] = {"h": ascent + descent, "ascent": ascent, "g": {}}
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        img = Image.new("1", (adv + 4, ascent + descent), 0)
        ImageDraw.Draw(img).text((1, 0), ch, font=font, fill=1)
        rows = []
        for y in range(img.height):
            bits = "".join("1" if img.getpixel((x, y)) else "0" for x in range(img.width))
            rows.append(bits)
        out["g"][ch] = {"adv": adv, "rows": rows}  # type: ignore[index]
    return out


def main() -> None:
    data = {name: glyphs(*spec) for name, spec in SIZES.items()}
    blob = base64.b64encode(zlib.compress(json.dumps(data, sort_keys=True).encode(), 9)).decode()
    lines = [blob[i : i + 96] for i in range(0, len(blob), 96)]
    body = "\n".join(f'    "{ln}"' for ln in lines)
    target = os.path.join("src", "sie", "workspace", "_font_data.py")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            '"""Glyph bitmaps for the PNG export (generated by tools/make_font.py; do not edit)."""\n\n'
            f"DATA = (\n{body}\n)\n"
        )
    print(target, len(blob))


if __name__ == "__main__":
    main()
